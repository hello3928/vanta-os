const DICTS = { en, es, fr, de, 'pt-BR': ptBR, ja };

let lang = 'en';
const listeners = [];

export const i18n = {
  get lang() {
    return lang;
  },
  set(code) {
    if (!DICTS[code] || code === lang) return;
    lang = code;
    document.documentElement.lang = code;
    listeners.forEach((fn) => fn(code));
  },
  onChange(fn) {
    listeners.push(fn);
  },
};

// t('hoursPlayed', { n: 3 }) → "3 hours played". Uses key_one for a count of 1 where it exists.
export function t(key, vars = {}) {
  const dict = DICTS[lang];
  const plural = 'n' in vars && new Intl.PluralRules(lang).select(vars.n) === 'one' ? `${key}_one` : null;
  let s = (plural && (dict[plural] ?? en[plural])) || dict[key] || en[key] || key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

// Display name for a setting value stored in English ('Off', 'High', ...).
export function opt(value) {
  return DICTS[lang].opt?.[value] ?? value;
}

// Days ago → "today", "yesterday", "3 weeks ago", "2 months ago" in the current language.
export function relDays(days) {
  if (days == null) return t('never');
  const rtf = new Intl.RelativeTimeFormat(lang, { numeric: 'auto' });
  if (days < 7) return rtf.format(-days, 'day');
  if (days < 30) return rtf.format(-Math.round(days / 7), 'week');
  return rtf.format(-Math.round(days / 30), 'month');
}

// "2 h 40 min" style durations.
export function duration(minutes) {
  const fmt = (v, unit) => new Intl.NumberFormat(lang, { style: 'unit', unit, unitDisplay: 'narrow' }).format(v);
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  return [h ? fmt(h, 'hour') : '', m ? fmt(m, 'minute') : ''].filter(Boolean).join(' ');
}
